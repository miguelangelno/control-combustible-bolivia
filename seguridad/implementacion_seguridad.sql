-- 1. PERMISOS PARA PROYECTO_SEG

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE
TO PROYECTO_SEG;

ALTER USER PROYECTO_SEG QUOTA UNLIMITED ON USERS;


-- 2. PERFIL DE SEGURIDAD
-- CREATE PROFILE se ejecuta una sola vez.

CREATE PROFILE perfil_seguridad LIMIT
    FAILED_LOGIN_ATTEMPTS 3
    PASSWORD_LOCK_TIME 1
    PASSWORD_LIFE_TIME 90
    PASSWORD_GRACE_TIME 7;

-- Asignar el perfil al usuario del proyecto.

ALTER USER PROYECTO_SEG PROFILE perfil_seguridad;


-- ============================================
-- PARTE B: AUDITORIA
-- EJECUTAR COMO PROYECTO_SEG
-- ============================================

-- 1. TABLA DE AUDITORIA

CREATE TABLE auditoria_persona (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    usuario_bd VARCHAR2(128),
    operacion VARCHAR2(10),
    fecha_operacion TIMESTAMP DEFAULT SYSTIMESTAMP,
    id_persona NUMBER,
    datos_anteriores VARCHAR2(4000),
    datos_nuevos VARCHAR2(4000)
);


-- 2. TRIGGER DE AUDITORIA

CREATE OR REPLACE TRIGGER trg_auditoria_persona
AFTER INSERT OR UPDATE OR DELETE ON persona
FOR EACH ROW
DECLARE
    v_operacion VARCHAR2(10);
    v_id_persona NUMBER;
    v_anteriores VARCHAR2(4000);
    v_nuevos VARCHAR2(4000);
BEGIN
    IF INSERTING THEN
        v_operacion := 'INSERT';
        v_id_persona := :NEW.id_persona;

        v_nuevos := 'CI=' || :NEW.ci ||
                    '; Nombres=' || :NEW.nombres ||
                    '; Apellidos=' || :NEW.apellidos;

    ELSIF UPDATING THEN
        v_operacion := 'UPDATE';
        v_id_persona := :NEW.id_persona;

        v_anteriores := 'CI=' || :OLD.ci ||
                        '; Nombres=' || :OLD.nombres ||
                        '; Apellidos=' || :OLD.apellidos;

        v_nuevos := 'CI=' || :NEW.ci ||
                    '; Nombres=' || :NEW.nombres ||
                    '; Apellidos=' || :NEW.apellidos;

    ELSE
        v_operacion := 'DELETE';
        v_id_persona := :OLD.id_persona;

        v_anteriores := 'CI=' || :OLD.ci ||
                        '; Nombres=' || :OLD.nombres ||
                        '; Apellidos=' || :OLD.apellidos;
    END IF;

    INSERT INTO auditoria_persona (
        usuario_bd,
        operacion,
        id_persona,
        datos_anteriores,
        datos_nuevos
    ) VALUES (
        SYS_CONTEXT('USERENV', 'SESSION_USER'),
        v_operacion,
        v_id_persona,
        v_anteriores,
        v_nuevos
    );
END;
/


-- ============================================
-- PARTE C: VISTAS DE SEGURIDAD
-- EJECUTAR COMO PROYECTO_SEG
-- ============================================

-- 1. VISTA DE PERSONAS PUBLICAS
-- No muestra CI, telefono ni correo.

CREATE OR REPLACE VIEW vista_personas_publicas AS
SELECT
    id_persona,
    nombres,
    apellidos
FROM persona
WHERE activa = 1;


-- 2. VISTA DE PERSONAS ACTIVAS
-- Incluye telefono, pero no CI ni correo.

CREATE OR REPLACE VIEW vista_personas_activas AS
SELECT
    id_persona,
    nombres,
    apellidos,
    telefono
FROM persona
WHERE activa = 1;

