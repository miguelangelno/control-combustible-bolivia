CREATE TABLE "persona" (
  "id_persona" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ci" varchar(20) UNIQUE NOT NULL,
  "nombres" varchar(100) NOT NULL,
  "apellidos" varchar(100) NOT NULL,
  "fecha_nacimiento" date,
  "telefono" varchar(20),
  "correo" varchar(120),
  "activa" boolean NOT NULL DEFAULT true,
  "fecha_registro" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "huella_digital" (
  "id_huella" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_persona" integer NOT NULL,
  "dedo" dedo_huella NOT NULL,
  "plantilla_cifrada" bytea NOT NULL,
  "fecha_registro" timestamp NOT NULL DEFAULT (now()),
  "activa" boolean NOT NULL DEFAULT true
);

CREATE TABLE "modelo_vehiculo" (
  "id_modelo" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "marca" varchar(60) NOT NULL,
  "nombre" varchar(80) NOT NULL,
  "anio_modelo" integer NOT NULL,
  "cilindrada_cc" integer NOT NULL,
  "tipo_vehiculo" varchar(30),
  "tipo_combustible" tipo_combustible NOT NULL,
  "capacidad_tanque_litros" decimal(7,2) NOT NULL,
  "consumo_km_por_litro" decimal(6,2),
  "autonomia_horas_tanque_lleno" decimal(7,2)
);

CREATE TABLE "vehiculo" (
  "id_vehiculo" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_modelo" integer NOT NULL,
  "id_persona" integer NOT NULL,
  "placa" varchar(10) UNIQUE NOT NULL,
  "codigo_rfid" varchar(64) UNIQUE NOT NULL,
  "nro_chasis" varchar(30) UNIQUE,
  "color" varchar(30),
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "regla_negocio" (
  "id_regla" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "codigo" varchar(50) NOT NULL,
  "descripcion" varchar(255) NOT NULL,
  "tipo_combustible" tipo_combustible,
  "valor_numerico" decimal(12,2) NOT NULL,
  "vigente_desde" timestamp NOT NULL,
  "vigente_hasta" timestamp,
  "activa" boolean NOT NULL DEFAULT true
);

CREATE TABLE "precio_combustible" (
  "id_precio" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tipo_combustible" tipo_combustible NOT NULL,
  "tipo_precio" tipo_precio NOT NULL,
  "precio_unidad" decimal(8,2) NOT NULL,
  "vigente_desde" timestamp NOT NULL,
  "vigente_hasta" timestamp
);

CREATE TABLE "subvencion_vehiculo" (
  "id_subvencion" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_persona" integer NOT NULL,
  "id_vehiculo" integer NOT NULL,
  "id_regla" integer,
  "litros_asignados" decimal(10,2) NOT NULL,
  "litros_consumidos" decimal(10,2) NOT NULL DEFAULT 0,
  "estado" estado_subvencion NOT NULL DEFAULT 'VIGENTE',
  "fecha_asignacion" timestamp NOT NULL DEFAULT (now()),
  "fecha_agotamiento" timestamp
);

CREATE TABLE "sucursal" (
  "id_sucursal" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "codigo_anh" varchar(30) UNIQUE NOT NULL,
  "nombre" varchar(120) NOT NULL,
  "empresa" varchar(150) NOT NULL,
  "departamento" varchar(30) NOT NULL,
  "ciudad" varchar(80) NOT NULL,
  "direccion" varchar(200),
  "latitud" decimal(9,6) NOT NULL,
  "longitud" decimal(9,6) NOT NULL,
  "activa" boolean NOT NULL DEFAULT true
);

CREATE TABLE "surtidor" (
  "id_surtidor" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_sucursal" integer NOT NULL,
  "numero" integer NOT NULL,
  "tipo_combustible" tipo_combustible NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "despacho_ypfb" (
  "id_despacho" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_sucursal" integer NOT NULL,
  "tipo_combustible" tipo_combustible NOT NULL,
  "planta_origen" varchar(100) NOT NULL,
  "litros" decimal(12,2) NOT NULL,
  "placa_cisterna" varchar(10),
  "fecha_hora" timestamp NOT NULL
);

CREATE TABLE "inspeccion_anh" (
  "id_inspeccion" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_sucursal" integer NOT NULL,
  "inspector" varchar(100) NOT NULL,
  "fecha_hora" timestamp NOT NULL,
  "resultado" resultado_inspeccion NOT NULL,
  "observaciones" text
);

CREATE TABLE "transaccion_carga" (
  "id_transaccion" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_surtidor" integer NOT NULL,
  "id_persona" integer NOT NULL,
  "id_huella" integer NOT NULL,
  "id_vehiculo" integer,
  "id_subvencion" integer,
  "tipo_carga" tipo_carga NOT NULL DEFAULT 'VEHICULO',
  "litros_total" decimal(8,2) NOT NULL,
  "litros_subvencionados" decimal(8,2) NOT NULL DEFAULT 0,
  "litros_internacionales" decimal(8,2) NOT NULL DEFAULT 0,
  "precio_subvencionado" decimal(8,2),
  "precio_internacional" decimal(8,2),
  "monto_total" decimal(10,2) NOT NULL,
  "tanque_lleno" boolean NOT NULL DEFAULT false,
  "motivo_precio_internacional" motivo_precio_internacional,
  "estado" estado_transaccion NOT NULL DEFAULT 'APROBADA',
  "fecha_hora" timestamp NOT NULL DEFAULT (now()),
  "latitud" decimal(9,6),
  "longitud" decimal(9,6)
);

CREATE TABLE "carga_bidon" (
  "id_carga_bidon" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_transaccion" bigint NOT NULL,
  "capacidad_bidon_litros" decimal(6,2) NOT NULL,
  "cantidad_bidones" integer NOT NULL DEFAULT 1,
  "litros_cargados" decimal(8,2) NOT NULL,
  "uso_declarado" varchar(100)
);

CREATE TABLE "alerta_fraude" (
  "id_alerta" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_transaccion" bigint NOT NULL,
  "id_regla" integer,
  "tipo_alerta" tipo_alerta NOT NULL,
  "descripcion" varchar(255),
  "distancia_km" decimal(8,2),
  "tiempo_transcurrido_min" integer,
  "estado" estado_alerta NOT NULL DEFAULT 'ABIERTA',
  "fecha_alerta" timestamp NOT NULL DEFAULT (now()),
  "fecha_revision" timestamp
);

