-- Modelo combustible adaptado para Oracle 12c+
-- Los ENUM de PostgreSQL se reemplazan por VARCHAR2 + CHECK

CREATE TABLE persona (
  id_persona       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ci               VARCHAR2(20) NOT NULL,
  nombres          VARCHAR2(100) NOT NULL,
  apellidos        VARCHAR2(100) NOT NULL,
  fecha_nacimiento DATE,
  telefono         VARCHAR2(20),
  correo           VARCHAR2(120),
  activa           NUMBER(1) DEFAULT 1 NOT NULL CHECK (activa IN (0,1)),
  fecha_registro   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_persona_ci UNIQUE (ci)
);

CREATE TABLE huella_digital (
  id_huella         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_persona        INTEGER NOT NULL,
  dedo              VARCHAR2(20) NOT NULL
    CHECK (dedo IN ('PULGAR_DERECHO','INDICE_DERECHO','MEDIO_DERECHO',
                    'PULGAR_IZQUIERDO','INDICE_IZQUIERDO','MEDIO_IZQUIERDO')),
  plantilla_cifrada BLOB NOT NULL,
  fecha_registro    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  activa            NUMBER(1) DEFAULT 1 NOT NULL CHECK (activa IN (0,1))
);

CREATE TABLE modelo_vehiculo (
  id_modelo                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca                        VARCHAR2(60) NOT NULL,
  nombre                       VARCHAR2(80) NOT NULL,
  anio_modelo                  INTEGER NOT NULL,
  cilindrada_cc                INTEGER NOT NULL,
  tipo_vehiculo                VARCHAR2(30),
  tipo_combustible             VARCHAR2(10) NOT NULL
    CHECK (tipo_combustible IN ('GASOLINA','DIESEL','GAS')),
  capacidad_tanque_litros      NUMBER(7,2) NOT NULL,
  consumo_km_por_litro         NUMBER(6,2),
  autonomia_horas_tanque_lleno NUMBER(7,2)
);

CREATE TABLE vehiculo (
  id_vehiculo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_modelo   INTEGER NOT NULL,
  id_persona  INTEGER NOT NULL,
  placa       VARCHAR2(10) NOT NULL,
  codigo_rfid VARCHAR2(64) NOT NULL,
  nro_chasis  VARCHAR2(30),
  color       VARCHAR2(30),
  activo      NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1)),
  CONSTRAINT uq_vehiculo_placa UNIQUE (placa),
  CONSTRAINT uq_vehiculo_rfid UNIQUE (codigo_rfid),
  CONSTRAINT uq_vehiculo_chasis UNIQUE (nro_chasis)
);

CREATE TABLE regla_negocio (
  id_regla         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo           VARCHAR2(50) NOT NULL,
  descripcion      VARCHAR2(255) NOT NULL,
  tipo_combustible VARCHAR2(10) CHECK (tipo_combustible IN ('GASOLINA','DIESEL','GAS')),
  valor_numerico   NUMBER(12,2) NOT NULL,
  vigente_desde    TIMESTAMP NOT NULL,
  vigente_hasta    TIMESTAMP,
  activa           NUMBER(1) DEFAULT 1 NOT NULL CHECK (activa IN (0,1))
);

CREATE TABLE precio_combustible (
  id_precio        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_combustible VARCHAR2(10) NOT NULL
    CHECK (tipo_combustible IN ('GASOLINA','DIESEL','GAS')),
  tipo_precio      VARCHAR2(15) NOT NULL
    CHECK (tipo_precio IN ('SUBVENCIONADO','INTERNACIONAL')),
  precio_unidad    NUMBER(8,2) NOT NULL,
  vigente_desde    TIMESTAMP NOT NULL,
  vigente_hasta    TIMESTAMP
);

CREATE TABLE subvencion_vehiculo (
  id_subvencion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_persona        INTEGER NOT NULL,
  id_vehiculo       INTEGER NOT NULL,
  id_regla          INTEGER,
  litros_asignados  NUMBER(10,2) NOT NULL,
  litros_consumidos NUMBER(10,2) DEFAULT 0 NOT NULL,
  estado            VARCHAR2(12) DEFAULT 'VIGENTE' NOT NULL
    CHECK (estado IN ('VIGENTE','AGOTADA','SUSPENDIDA','BAJA')),
  fecha_asignacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  fecha_agotamiento TIMESTAMP
);

CREATE TABLE sucursal (
  id_sucursal  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_anh   VARCHAR2(30) NOT NULL,
  nombre       VARCHAR2(120) NOT NULL,
  empresa      VARCHAR2(150) NOT NULL,
  departamento VARCHAR2(30) NOT NULL,
  ciudad       VARCHAR2(80) NOT NULL,
  direccion    VARCHAR2(200),
  latitud      NUMBER(9,6) NOT NULL,
  longitud     NUMBER(9,6) NOT NULL,
  activa       NUMBER(1) DEFAULT 1 NOT NULL CHECK (activa IN (0,1)),
  CONSTRAINT uq_sucursal_anh UNIQUE (codigo_anh)
);

CREATE TABLE surtidor (
  id_surtidor      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sucursal      INTEGER NOT NULL,
  numero           INTEGER NOT NULL,
  tipo_combustible VARCHAR2(10) NOT NULL
    CHECK (tipo_combustible IN ('GASOLINA','DIESEL','GAS')),
  activo           NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1))
);

CREATE TABLE despacho_ypfb (
  id_despacho      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sucursal      INTEGER NOT NULL,
  tipo_combustible VARCHAR2(10) NOT NULL
    CHECK (tipo_combustible IN ('GASOLINA','DIESEL','GAS')),
  planta_origen    VARCHAR2(100) NOT NULL,
  litros           NUMBER(12,2) NOT NULL,
  placa_cisterna   VARCHAR2(10),
  fecha_hora       TIMESTAMP NOT NULL
);

CREATE TABLE inspeccion_anh (
  id_inspeccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sucursal   INTEGER NOT NULL,
  inspector     VARCHAR2(100) NOT NULL,
  fecha_hora    TIMESTAMP NOT NULL,
  resultado     VARCHAR2(12) NOT NULL
    CHECK (resultado IN ('CONFORME','OBSERVADA','PRECINTADA')),
  observaciones CLOB
);

CREATE TABLE transaccion_carga (
  id_transaccion              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_surtidor                 INTEGER NOT NULL,
  id_persona                  INTEGER NOT NULL,
  id_huella                   INTEGER NOT NULL,
  id_vehiculo                 INTEGER,
  id_subvencion               INTEGER,
  tipo_carga                  VARCHAR2(10) DEFAULT 'VEHICULO' NOT NULL
    CHECK (tipo_carga IN ('VEHICULO','BIDON')),
  litros_total                NUMBER(8,2) NOT NULL,
  litros_subvencionados       NUMBER(8,2) DEFAULT 0 NOT NULL,
  litros_internacionales      NUMBER(8,2) DEFAULT 0 NOT NULL,
  precio_subvencionado        NUMBER(8,2),
  precio_internacional        NUMBER(8,2),
  monto_total                 NUMBER(10,2) NOT NULL,
  tanque_lleno                NUMBER(1) DEFAULT 0 NOT NULL CHECK (tanque_lleno IN (0,1)),
  motivo_precio_internacional VARCHAR2(30)
    CHECK (motivo_precio_internacional IN ('CUPO_AGOTADO','NO_ES_TITULAR',
      'VEHICULO_SIN_SUBVENCION','LIMITE_VEHICULOS_EXCEDIDO','CARGA_EN_BIDON')),
  estado                      VARCHAR2(10) DEFAULT 'APROBADA' NOT NULL
    CHECK (estado IN ('APROBADA','RECHAZADA','ANULADA')),
  fecha_hora                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  latitud                     NUMBER(9,6),
  longitud                    NUMBER(9,6)
);

CREATE TABLE carga_bidon (
  id_carga_bidon         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaccion         NUMBER(19) NOT NULL,
  capacidad_bidon_litros NUMBER(6,2) NOT NULL,
  cantidad_bidones       INTEGER DEFAULT 1 NOT NULL,
  litros_cargados        NUMBER(8,2) NOT NULL,
  uso_declarado          VARCHAR2(100)
);

CREATE TABLE alerta_fraude (
  id_alerta               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaccion          NUMBER(19) NOT NULL,
  id_regla                INTEGER,
  tipo_alerta             VARCHAR2(30) NOT NULL
    CHECK (tipo_alerta IN ('UBICACION_IMPOSIBLE','FRECUENCIA_EXCEDIDA',
                           'EXCEDE_CAPACIDAD_TANQUE','USO_BIDON_SOSPECHOSO')),
  descripcion             VARCHAR2(255),
  distancia_km            NUMBER(8,2),
  tiempo_transcurrido_min INTEGER,
  estado                  VARCHAR2(12) DEFAULT 'ABIERTA' NOT NULL
    CHECK (estado IN ('ABIERTA','EN_REVISION','CERRADA')),
  fecha_alerta            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  fecha_revision          TIMESTAMP
);

-- Indices
CREATE UNIQUE INDEX ux_huella_persona_dedo ON huella_digital (id_persona, dedo);
CREATE UNIQUE INDEX ux_modelo_veh ON modelo_vehiculo (marca, nombre, anio_modelo, cilindrada_cc);
CREATE UNIQUE INDEX ux_regla_cod ON regla_negocio (codigo, tipo_combustible, vigente_desde);
CREATE UNIQUE INDEX ux_precio_comb ON precio_combustible (tipo_combustible, tipo_precio, vigente_desde);
CREATE INDEX ix_subv_persona ON subvencion_vehiculo (id_persona, estado);
CREATE INDEX ix_subv_vehiculo ON subvencion_vehiculo (id_vehiculo, estado);
CREATE INDEX ix_sucursal_ubic ON sucursal (departamento, ciudad);
CREATE UNIQUE INDEX ux_surtidor_num ON surtidor (id_sucursal, numero);
CREATE INDEX ix_despacho_suc ON despacho_ypfb (id_sucursal, fecha_hora);
CREATE INDEX ix_inspeccion_suc ON inspeccion_anh (id_sucursal, fecha_hora);
CREATE INDEX ix_trx_vehiculo ON transaccion_carga (id_vehiculo, fecha_hora);
CREATE INDEX ix_trx_persona ON transaccion_carga (id_persona, fecha_hora);
CREATE INDEX ix_trx_surtidor ON transaccion_carga (id_surtidor, fecha_hora);
CREATE INDEX ix_alerta_estado ON alerta_fraude (estado, fecha_alerta);

